CREATE TABLE IF NOT EXISTS COLLECTION
(
    ID varchar NOT NULL PRIMARY KEY,
    NAME varchar NOT NULL,
    ORDERED boolean NOT NULL,
    SERIES_COUNT int NOT NULL DEFAULT 0,
    CREATED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_MODIFIED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS idx__collection__name ON COLLECTION (NAME COLLATE NOCASE);

CREATE TABLE IF NOT EXISTS COLLECTION_SERIES
(
    COLLECTION_ID varchar NOT NULL,
    SERIES_ID varchar NOT NULL,
    NUMBER int NOT NULL,
    PRIMARY KEY (COLLECTION_ID, SERIES_ID),
    FOREIGN KEY (COLLECTION_ID) REFERENCES COLLECTION (ID) ON DELETE CASCADE,
    FOREIGN KEY (SERIES_ID) REFERENCES SERIES (ID) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx__collection_series__collection_id ON COLLECTION_SERIES (COLLECTION_ID);
CREATE INDEX IF NOT EXISTS idx__collection_series__series_id ON COLLECTION_SERIES (SERIES_ID);
CREATE UNIQUE INDEX IF NOT EXISTS idx__collection_series__number ON COLLECTION_SERIES (COLLECTION_ID, NUMBER);

CREATE TABLE IF NOT EXISTS READLIST
(
    ID varchar NOT NULL PRIMARY KEY,
    NAME varchar NOT NULL,
    SUMMARY varchar NOT NULL DEFAULT '',
    ORDERED boolean NOT NULL DEFAULT 1,
    BOOK_COUNT int NOT NULL DEFAULT 0,
    CREATED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_MODIFIED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS idx__readlist__name ON READLIST (NAME COLLATE NOCASE);

CREATE TABLE IF NOT EXISTS READLIST_BOOK
(
    READLIST_ID varchar NOT NULL,
    BOOK_ID varchar NOT NULL,
    NUMBER int NOT NULL,
    PRIMARY KEY (READLIST_ID, BOOK_ID),
    FOREIGN KEY (READLIST_ID) REFERENCES READLIST (ID) ON DELETE CASCADE,
    FOREIGN KEY (BOOK_ID) REFERENCES BOOK (ID) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx__readlist_book__readlist_id ON READLIST_BOOK (READLIST_ID);
CREATE INDEX IF NOT EXISTS idx__readlist_book__book_id ON READLIST_BOOK (BOOK_ID);
CREATE UNIQUE INDEX IF NOT EXISTS idx__readlist_book__number ON READLIST_BOOK (READLIST_ID, NUMBER);

CREATE TABLE IF NOT EXISTS THUMBNAIL_COLLECTION
(
    ID varchar NOT NULL PRIMARY KEY, URL varchar NULL, SELECTED boolean NOT NULL DEFAULT 0,
    THUMBNAIL blob NULL, TYPE varchar NOT NULL, CREATED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_MODIFIED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP, COLLECTION_ID varchar NOT NULL,
    WIDTH int NOT NULL DEFAULT 0, HEIGHT int NOT NULL DEFAULT 0, MEDIA_TYPE varchar NOT NULL DEFAULT '',
    FILE_SIZE int8 NOT NULL DEFAULT 0,
    FOREIGN KEY (COLLECTION_ID) REFERENCES COLLECTION (ID) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx__thumbnail_collection__collection_id ON THUMBNAIL_COLLECTION (COLLECTION_ID);

CREATE TABLE IF NOT EXISTS THUMBNAIL_READLIST
(
    ID varchar NOT NULL PRIMARY KEY, URL varchar NULL, SELECTED boolean NOT NULL DEFAULT 0,
    THUMBNAIL blob NULL, TYPE varchar NOT NULL, CREATED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_MODIFIED_DATE datetime NOT NULL DEFAULT CURRENT_TIMESTAMP, READLIST_ID varchar NOT NULL,
    WIDTH int NOT NULL DEFAULT 0, HEIGHT int NOT NULL DEFAULT 0, MEDIA_TYPE varchar NOT NULL DEFAULT '',
    FILE_SIZE int8 NOT NULL DEFAULT 0,
    FOREIGN KEY (READLIST_ID) REFERENCES READLIST (ID) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx__thumbnail_readlist__readlist_id ON THUMBNAIL_READLIST (READLIST_ID);
