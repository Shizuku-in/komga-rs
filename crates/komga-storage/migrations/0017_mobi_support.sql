ALTER TABLE LIBRARY ADD COLUMN SCAN_MOBI boolean NOT NULL DEFAULT 1;

UPDATE MEDIA
   SET STATUS = 'OUTDATED',
       LAST_MODIFIED_DATE = CURRENT_TIMESTAMP
 WHERE STATUS = 'UNSUPPORTED'
   AND (
       MEDIA_TYPE = 'application/x-mobipocket-ebook'
       OR lower((SELECT URL FROM BOOK WHERE BOOK.ID = MEDIA.BOOK_ID)) LIKE '%.mobi'
   );
